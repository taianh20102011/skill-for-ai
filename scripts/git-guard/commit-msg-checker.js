#!/usr/bin/env node

/**
 * Smart Commit Message Checker (Conventional Commits Guard)
 * Validates commit messages according to the Conventional Commits specification.
 * Usage: node commit-msg-checker.js <commit-msg-file-or-string>
 */

const fs = require('fs');
const path = require('path');

const colors = {
  reset: '\x1b[0m',
  bright: '\x1b[1m',
  dim: '\x1b[2m',
  red: '\x1b[31m',
  green: '\x1b[32m',
  yellow: '\x1b[33m',
  blue: '\x1b[34m',
  cyan: '\x1b[36m',
  gray: '\x1b[90m',
};

const ALLOWED_TYPES = [
  'feat',     // Tính năng mới
  'fix',      // Sửa lỗi
  'docs',     // Tài liệu
  'style',    // Định dạng, khoảng trắng (không ảnh hưởng logic)
  'refactor', // Tái cấu trúc mã nguồn
  'perf',     // Cải thiện hiệu năng
  'test',     // Bổ sung hoặc sửa đổi bài test
  'build',    // Thay đổi ảnh hưởng hệ thống build hoặc dependency
  'ci',       // Thay đổi file cấu hình CI/CD
  'chore',    // Công việc vặt, bảo trì
  'revert',   // Hoàn tác commit trước đó
];

// Conventional Commits regex pattern:
// type(scope?)!?: description
const COMMIT_REGEX = /^(?<type>[a-z]+)(?:\((?<scope>[a-zA-Z0-9_\-\.\/]+)\))?(?<breaking>!)?:\s+(?<subject>[^\n\r]+)/;

function getCommitMessage() {
  const arg = process.argv[2];
  if (!arg) {
    console.error(`${colors.red}❌ Lỗi: Không tìm thấy nội dung commit message để kiểm tra.${colors.reset}`);
    process.exit(1);
  }

  // If argument is a file path (as provided by git hook commit-msg)
  if (fs.existsSync(arg)) {
    return fs.readFileSync(arg, 'utf-8').trim();
  }

  return arg.trim();
}

function validateCommitMessage(message) {
  // Ignore merge / revert commits generated by git
  if (message.startsWith('Merge branch') || message.startsWith('Merge pull request') || message.startsWith('Revert "')) {
    return { valid: true };
  }

  // Get first line (subject line)
  const lines = message.split('\n');
  const header = lines[0].trim();

  if (!header) {
    return {
      valid: false,
      errors: ['Commit message không được để trống.']
    };
  }

  const errors = [];

  // Check max length
  if (header.length > 100) {
    errors.push(`Dòng tiêu đề quá dài (${header.length}/100 ký tự). Hãy giữ ngắn gọn và chuyển chi tiết vào phần body.`);
  }

  const match = header.match(COMMIT_REGEX);
  if (!match) {
    errors.push(`Tiêu đề không tuân thủ định dạng Conventional Commits: <type>(<scope?>): <description>`);
  } else {
    const { type, scope, subject } = match.groups;

    if (!ALLOWED_TYPES.includes(type)) {
      errors.push(`Loại commit '${type}' không hợp lệ. Các loại cho phép: [${ALLOWED_TYPES.join(', ')}]`);
    }

    if (subject.endsWith('.')) {
      errors.push(`Mô tả commit không được kết thúc bằng dấu chấm ('.').`);
    }

    if (subject.length < 3) {
      errors.push(`Mô tả commit quá ngắn (tối thiểu 3 ký tự).`);
    }

    if (subject[0] === subject[0].toUpperCase() && subject[0] !== subject[0].toLowerCase()) {
      // Warning for uppercase start in subject
      // Non-blocking but good practice
    }
  }

  return {
    valid: errors.length === 0,
    errors,
    header
  };
}

function run() {
  const rawMsg = getCommitMessage();
  const result = validateCommitMessage(rawMsg);

  if (result.valid) {
    console.log(`${colors.green}✔ [Commit Guard]${colors.reset} Commit message hợp lệ: ${colors.cyan}"${result.header || rawMsg}"${colors.reset}`);
    process.exit(0);
  } else {
    console.log(`\n${colors.red}${colors.bright}========================================================================${colors.reset}`);
    console.log(`${colors.red}${colors.bright} ❌ [COMMIT GUARD BỊ TỪ CHỐI] COMMIT MESSAGE SAI ĐỊNH DẠNG${colors.reset}`);
    console.log(`${colors.red}${colors.bright}========================================================================${colors.reset}\n`);

    console.log(`${colors.bright}Nội dung đã nhập:${colors.reset} ${colors.yellow}"${rawMsg}"${colors.reset}\n`);
    console.log(`${colors.bright}Các lỗi vi phạm:${colors.reset}`);
    result.errors.forEach(err => console.log(`  ${colors.red}• ${err}${colors.reset}`));

    console.log(`\n${colors.bright}Chuẩn quy ước Conventional Commits:${colors.reset}`);
    console.log(`  ${colors.cyan}<type>(<phạm_vi?>): <mô tả ngắn gọn>${colors.reset}`);

    console.log(`\n${colors.bright}Ví dụ đúng chuẩn:${colors.reset}`);
    console.log(`  ${colors.green}feat(auth): thêm xác thực 2FA OTP qua Gmail${colors.reset}`);
    console.log(`  ${colors.green}fix(ui): sửa lỗi tràn viền trên màn hình mobile${colors.reset}`);
    console.log(`  ${colors.green}perf(gsap): tối ưu animation 120fps cho hero section${colors.reset}`);
    console.log(`  ${colors.green}docs(readme): cập nhật hướng dẫn cài đặt CLI${colors.reset}\n`);

    process.exit(1);
  }
}

if (require.main === module) {
  run();
}

module.exports = { validateCommitMessage, ALLOWED_TYPES };
